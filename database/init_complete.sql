COMMENT ON TABLE public.log_penanganan IS 'Admin action logs for report handling';

-- 4.6 REPORT REPLIES TABLE
-- Admin responses to students
CREATE TABLE public.balasan_laporan (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id BIGINT NOT NULL REFERENCES public.reports(id),
  author_id UUID NOT NULL REFERENCES public.profiles(id),
  pesan TEXT NOT NULL,                                     -- Reply message
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
