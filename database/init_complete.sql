-- 6.1 Helper function to get current user's role
CREATE OR REPLACE FUNCTION public.get_my_role()
RETURNS TEXT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  RETURN (
    SELECT role::text FROM public.profiles WHERE id = auth.uid()
  );
END;
$$;

-- 6.2 Function to auto-create user profile on signup
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  INSERT INTO public.profiles (id, full_name, role)
  VALUES (new.id, new.raw_user_meta_data->>'full_name', 'siswa');
  RETURN new;
END;
$$;

-- 6.3 Function to get report status counts for dashboard
CREATE OR REPLACE FUNCTION get_report_status_counts()
RETURNS TABLE(status TEXT, total BIGINT) AS $$
BEGIN
  RETURN QUERY
  SELECT r.status::TEXT, COUNT(*) as total
  FROM public.reports r
  GROUP BY r.status;
END;
$$ LANGUAGE plpgsql;

-- 6.4 Function to create new report with evidence
CREATE OR REPLACE FUNCTION create_new_report(
  title TEXT,
  description TEXT,
  is_anonymous BOOLEAN,
  evidence_urls TEXT[]
)
RETURNS void AS $$
DECLARE
  new_report_id BIGINT;
BEGIN
  -- Insert report
  INSERT INTO public.reports (title, description, is_anonymous, reporter_id)
  VALUES (
    title,
    description,
    is_anonymous,
    CASE WHEN is_anonymous THEN NULL ELSE auth.uid() END
  ) RETURNING id INTO new_report_id;

  -- Insert evidence if provided
  IF array_length(evidence_urls, 1) > 0 THEN
    FOR i IN 1..array_length(evidence_urls, 1) LOOP
      INSERT INTO public.evidence (report_id, file_url, file_type)
      VALUES (new_report_id, evidence_urls[i], 'image/jpeg');
    END LOOP;
  END IF;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- 6.5 Function to auto-update updated_at column
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ language 'plpgsql';

