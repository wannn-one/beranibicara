-- 4.1 CLASSES TABLE
-- Master data for school classes
CREATE TABLE public.kelas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tingkat INT NOT NULL,                                    -- Grade level (1-6)
  jurusan TEXT NOT NULL,                                   -- Class section (A, B, C, etc.)
  wali_kelas_id UUID REFERENCES auth.users(id),           -- Homeroom teacher ID
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  
  -- Ensure unique combination of grade and section
  CONSTRAINT kelas_tingkat_jurusan_key UNIQUE(tingkat, jurusan)
);

COMMENT ON TABLE public.kelas IS 'Master data for school classes';
COMMENT ON COLUMN public.kelas.wali_kelas_id IS 'ID of the homeroom teacher';

-- 4.2 USER PROFILES TABLE
-- Extended user information linked to auth.users
CREATE TABLE public.profiles (
  id uuid NOT NULL PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  full_name text,
  role user_role NOT NULL DEFAULT 'siswa',
  kelas_id BIGINT REFERENCES public.kelas(id),            -- Student's class
  created_at timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.profiles IS 'Extended user profile information';
COMMENT ON COLUMN public.profiles.id IS 'Primary key linked to auth.users.id';
COMMENT ON COLUMN public.profiles.kelas_id IS 'Class ID where student is enrolled';

-- 4.3 REPORTS TABLE
-- Core table for bullying reports
CREATE TABLE public.reports (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reporter_id uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  title TEXT,                                              -- Report title
  description text NOT NULL CHECK (char_length(description) > 10),
  status report_status NOT NULL DEFAULT 'baru',
  is_anonymous boolean NOT NULL DEFAULT false,             -- Semi-anonymous flag
  created_at timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.reports IS 'Bullying reports submitted by users';
COMMENT ON COLUMN public.reports.reporter_id IS 'Reporter ID (can be NULL for anonymous reports)';
COMMENT ON COLUMN public.reports.title IS 'Short title for the report';
COMMENT ON COLUMN public.reports.is_anonymous IS 'Flag for semi-anonymous reports (name hidden from UI)';

-- 4.4 EVIDENCE TABLE
-- File attachments for reports
CREATE TABLE public.evidence (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id bigint NOT NULL REFERENCES public.reports(id) ON DELETE CASCADE,
  file_url text NOT NULL,
  file_type text,                                          -- MIME type
  created_at timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.evidence IS 'Evidence files attached to reports';
COMMENT ON COLUMN public.evidence.report_id IS 'Links evidence to specific report';

-- 4.5 HANDLING LOGS TABLE
-- Admin action logs for report processing
CREATE TABLE public.log_penanganan (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id BIGINT NOT NULL REFERENCES public.reports(id),
  author_id UUID NOT NULL REFERENCES public.profiles(id),
  catatan TEXT NOT NULL,                                   -- Action notes
  tahapan tahapan_enum NOT NULL,                          -- Handling stage
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
