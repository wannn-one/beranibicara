        (SELECT role FROM public.profiles WHERE id = auth.uid()) = 'tppk'
        OR
        (
            (SELECT role FROM public.profiles WHERE id = auth.uid()) = 'siswa'
            AND kelas_id = (SELECT kelas_id FROM public.profiles WHERE id = auth.uid())
        )
        OR
