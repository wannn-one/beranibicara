ON public.reports FOR SELECT
TO authenticated
USING (reporter_id = auth.uid());

CREATE POLICY "Allow TPPK members to view all reports"
ON public.reports FOR SELECT TO authenticated USING (get_my_role() = 'tppk');

CREATE POLICY "Allow TPPK members to update all reports"
ON public.reports FOR UPDATE TO authenticated USING (get_my_role() = 'tppk');

CREATE POLICY "Allow teachers to view reports from their class"
ON public.reports FOR SELECT
TO authenticated
USING (
  get_my_role() = 'guru'
  AND is_anonymous = false
  AND (
    (SELECT p.kelas_id FROM public.profiles p WHERE p.id = reports.reporter_id) 
    = 
    (SELECT k.id FROM public.kelas k WHERE k.wali_kelas_id = auth.uid())
  )
);

