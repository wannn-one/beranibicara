-- Enable RLS
ALTER TABLE public.cerita_kelas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.tanggapan_cerita ENABLE ROW LEVEL SECURITY;

-- POLICIES UNTUK CERITA KELAS

-- 1. Siswa hanya bisa melihat cerita di kelas mereka sendiri
-- 2. Guru hanya bisa melihat cerita di kelas yang mereka wali
-- 3. Admin bisa melihat semua cerita
CREATE POLICY "Users can view stories in their class" ON public.cerita_kelas
    FOR SELECT USING (
        -- Admin bisa lihat semua
        (SELECT role FROM public.profiles WHERE id = auth.uid()) = 'tppk'
        OR
        -- Siswa bisa lihat cerita di kelas mereka
        (
            (SELECT role FROM public.profiles WHERE id = auth.uid()) = 'siswa'
            AND kelas_id = (SELECT kelas_id FROM public.profiles WHERE id = auth.uid())
        )
        OR
        -- Guru bisa lihat cerita di kelas yang mereka wali
        (
            (SELECT role FROM public.profiles WHERE id = auth.uid()) = 'guru'
            AND kelas_id IN (SELECT id FROM public.kelas WHERE wali_kelas_id = auth.uid())
        )
    );

-- Hanya siswa dan admin yang bisa membuat cerita
CREATE POLICY "Students and admins can create stories" ON public.cerita_kelas
    FOR INSERT WITH CHECK (
        author_id = auth.uid()
        AND (
            (SELECT role FROM public.profiles WHERE id = auth.uid()) = 'siswa'
            OR (SELECT role FROM public.profiles WHERE id = auth.uid()) = 'tppk'
        )
        AND (
            -- Siswa hanya bisa posting di kelas mereka sendiri
            (
                (SELECT role FROM public.profiles WHERE id = auth.uid()) = 'siswa'
                AND kelas_id = (SELECT kelas_id FROM public.profiles WHERE id = auth.uid())
            )
            OR
            -- Admin bisa posting di kelas manapun
            (SELECT role FROM public.profiles WHERE id = auth.uid()) = 'tppk'
        )
    );

-- Hanya author dan admin yang bisa update/delete cerita
CREATE POLICY "Authors and admins can update their stories" ON public.cerita_kelas
    FOR UPDATE USING (
        author_id = auth.uid()
        OR (SELECT role FROM public.profiles WHERE id = auth.uid()) = 'tppk'
    );

CREATE POLICY "Authors and admins can delete their stories" ON public.cerita_kelas
    FOR DELETE USING (
        author_id = auth.uid()
        OR (SELECT role FROM public.profiles WHERE id = auth.uid()) = 'tppk'
    );

-- POLICIES UNTUK TANGGAPAN CERITA

-- Bisa melihat tanggapan jika bisa melihat ceritanya
CREATE POLICY "Users can view responses if they can view the story" ON public.tanggapan_cerita
    FOR SELECT USING (
        EXISTS (
            SELECT 1 FROM public.cerita_kelas 
            WHERE id = cerita_id
            AND (
                -- Admin bisa lihat semua
                (SELECT role FROM public.profiles WHERE id = auth.uid()) = 'tppk'
                OR
                -- Siswa bisa lihat tanggapan cerita di kelas mereka
                (
                    (SELECT role FROM public.profiles WHERE id = auth.uid()) = 'siswa'
                    AND kelas_id = (SELECT kelas_id FROM public.profiles WHERE id = auth.uid())
                )
                OR
                -- Guru bisa lihat tanggapan cerita di kelas yang mereka wali
                (
                    (SELECT role FROM public.profiles WHERE id = auth.uid()) = 'guru'
                    AND kelas_id IN (SELECT id FROM public.kelas WHERE wali_kelas_id = auth.uid())
                )
            )
        )
    );

-- Semua user bisa memberikan tanggapan jika mereka bisa melihat ceritanya
CREATE POLICY "Users can create responses if they can view the story" ON public.tanggapan_cerita
    FOR INSERT WITH CHECK (
        author_id = auth.uid()
        AND EXISTS (
            SELECT 1 FROM public.cerita_kelas 
            WHERE id = cerita_id
            AND (
                -- Admin bisa tanggapi semua
                (SELECT role FROM public.profiles WHERE id = auth.uid()) = 'tppk'
                OR
                -- Siswa bisa tanggapi cerita di kelas mereka
                (
                    (SELECT role FROM public.profiles WHERE id = auth.uid()) = 'siswa'
                    AND kelas_id = (SELECT kelas_id FROM public.profiles WHERE id = auth.uid())
                )
                OR
                -- Guru bisa tanggapi cerita di kelas yang mereka wali
                (
                    (SELECT role FROM public.profiles WHERE id = auth.uid()) = 'guru'
                    AND kelas_id IN (SELECT id FROM public.kelas WHERE wali_kelas_id = auth.uid())
                )
            )
        )
    );

-- Hanya author dan admin yang bisa update/delete tanggapan
CREATE POLICY "Authors and admins can update their responses" ON public.tanggapan_cerita
    FOR UPDATE USING (
        author_id = auth.uid()
        OR (SELECT role FROM public.profiles WHERE id = auth.uid()) = 'tppk'
    );

CREATE POLICY "Authors and admins can delete their responses" ON public.tanggapan_cerita
    FOR DELETE USING (
        author_id = auth.uid()
        OR (SELECT role FROM public.profiles WHERE id = auth.uid()) = 'tppk'
    );

